        if item[1] == display then
            return item[3]
        end
    end
    return nil
end

-- 按显示文本查序号（1 基；找不到 → nil）
function M.index_of(display)
    for i, item in ipairs(M.items) do
        if item[1] == display then
            return i
        end
    end
    return nil
end

